def get(persona_id: str) -> dict:
    """คืน persona ตาม id — ไม่พบ → ValueError (ให้ผู้เรียกแปลงเป็น 400/บอกผู้ใช้)"""
    pid = (persona_id or "").strip().lower()
    if pid not in PERSONAS:
        raise ValueError(f"ไม่รู้จัก persona: {persona_id!r} (มี: {', '.join(PERSONAS)})")
    return {"id": pid, **PERSONAS[pid]}


def list_personas() -> list:
    """รายชื่อ persona ทั้งหมด (สำหรับหน้าเว็บ/CLI) — ไม่รวม prompt เต็ม"""
    return [{"id": pid, "name": p["name"], "title": p["title"], "skills": p["skills"]}
            for pid, p in PERSONAS.items()]


def system_prompt(persona_id: str) -> str:
    """ประกอบ system prompt ของ persona (ชื่อ+บทบาท+จุดแข็ง+วิธีคิด+กันการปลอมเป็นตัวจริง)"""
    p = get(persona_id)
    skills = ", ".join(p["skills"])
    return (f"คุณคือที่ปรึกษาเลนส์ '{p['name']}' — {p['title']}.\n"
            f"จุดแข็ง: {skills}.\n"
            f"{p['prompt']}.\n"
            f"ตอบกระชับ ตรงประเด็น เป็นภาษาไทย. "
            f"คุณเป็นเพียง 'เลนส์ความคิด' ตามหลักการสาธารณะ ไม่ใช่บุคคลจริง "
            f"และไม่อ้างว่าเป็นเขาหรืออ้างคำพูดจริงของเขา")
