export type ThKey = keyof typeof TH;

/** Looks up a dictionary string and fills {name} placeholders. */
export function tr(key: ThKey, vars?: Record<string, string | number>): string {
  const template: string = TH[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match: string, name: string) => (name in vars ? String(vars[name]) : match));
}
